"""The WKB/EWKB <-> GeoJSON <-> EWKT codec in `fastfort/admin/geo.py`.

Fixtures below are hex generated by PostGIS itself (`ST_AsBinary`/`ST_AsEWKB`,
both byte orders, `ST_SetSRID(..., 4326)` for the EWKB ones) rather than
hand-written, so a bug in this module's own encoder could not also be baked
into the fixture that is supposed to catch it. `POINT_WKB_LE`/`POINT_EWKB_LE`
below are the same two hex strings the geometry tests used before this module
existed (`TASHKENT_WKB`/`TASHKENT_EWKB`), confirming nothing moved.
"""

